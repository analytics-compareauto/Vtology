// Copies supabase/migrations/*.sql into the server package (so deployments can apply them) and
// rebuilds supabase/setup_all.sql. Run after adding a migration: npm run migrations:embed
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase/migrations');
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
const migrations = files.map(f => ({ id: f.replace(/\.sql$/, ''), sql: readFileSync(join(dir, f), 'utf8') }));

writeFileSync(join(root, 'packages/server/src/migrations.generated.ts'),
  `// Generated by scripts/embed-migrations.mjs from supabase/migrations. Do not edit by hand.\n` +
  `export const MIGRATIONS: { id: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`);

writeFileSync(join(root, 'supabase/setup_all.sql'),
  '-- Vtology: full database setup. Paste all of this into Supabase → SQL Editor → New query → Run.\n' +
  '-- (Deployed versions of Vtology also apply new migrations automatically on start.)\n' +
  migrations.map(m => `\n-- ===== ${m.id}.sql =====\n${m.sql}`).join('') +
  `\ncreate schema if not exists vt_meta;\ncreate table if not exists vt_meta.schema_migrations (id text primary key, applied_at timestamptz not null default now());\n` +
  `insert into vt_meta.schema_migrations (id) values ${migrations.map(m => `('${m.id}')`).join(', ')} on conflict do nothing;\n`);
console.log(`embedded ${migrations.length} migrations`);
